ALTER TABLE subscriptions
  ADD COLUMN IF NOT EXISTS app_store_environment TEXT;

CREATE TABLE IF NOT EXISTS app_store_transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  transaction_id TEXT NOT NULL,
  original_transaction_id TEXT,
  product_id TEXT NOT NULL,
  tier TEXT NOT NULL,
  environment TEXT NOT NULL CHECK (environment IN ('Production', 'Sandbox', 'Xcode')),
  verification_status TEXT NOT NULL CHECK (verification_status IN ('verified', 'simulated')),
  status TEXT NOT NULL CHECK (status IN ('active', 'expired', 'revoked', 'simulated')),
  event_type TEXT,
  event_subtype TEXT,
  transaction_date TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  is_test BOOLEAN GENERATED ALWAYS AS (environment <> 'Production') STORED,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (environment, transaction_id),
  CHECK (
    (environment = 'Xcode' AND verification_status = 'simulated' AND status = 'simulated')
    OR (environment IN ('Production', 'Sandbox') AND verification_status = 'verified' AND status <> 'simulated')
  )
);

ALTER TABLE app_store_transactions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users read own App Store transactions" ON app_store_transactions;
CREATE POLICY "Users read own App Store transactions"
  ON app_store_transactions FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users record own Xcode StoreKit simulations" ON app_store_transactions;
CREATE POLICY "Users record own Xcode StoreKit simulations"
  ON app_store_transactions FOR INSERT
  TO authenticated
  WITH CHECK (
    auth.uid() = user_id
    AND environment = 'Xcode'
    AND verification_status = 'simulated'
    AND status = 'simulated'
  );

GRANT SELECT, INSERT ON app_store_transactions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE app_store_transactions_id_seq TO authenticated;

NOTIFY pgrst, 'reload schema';
